public class EscapeSequences {
    public static void main(String[] args){
        System.out.println("This is a \t tab escape sequence");//Tabs

        System.out.println("This is a \b backspace sequence");//Backspace

        System.out.println("This is a \n newline"); //newline

        System.out.println("This is a single quote \" escape sequence");//quote

        System.out.println("This is a double quote \" \" escape sequence");

        System.out.println("This is a backslash \\ escape sequence"); //Backslash

        System.out.println("My name is \"Alan\"");
    }
}
